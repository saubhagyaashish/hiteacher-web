// Helper functions for mock data
export function getContentById(id: string): Content | undefined {
    return mockContent.find(c => c.id === id)
}

export function getContentByTeacherId(teacherId: string): Content[] {
    return mockContent.filter(c => c.teacherId === teacherId)
}

export function getContentByBatchId(batchId: string): Content[] {
    return mockContent.filter(c => c.batchIds.includes(batchId))
}
